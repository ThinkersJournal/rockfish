//! Tests for [`rockfish_hip_emit::Hip`].
//!
//! **What these show.** The emitted text is what the golden says, parses back through
//! `rockfish-hip-parse` to the IR it came from, and the refusals are typed. **What they do not
//! show:** that any of it compiles or computes the right numbers on a GPU. No HIP compiler was
//! run (none on this machine); the rig row in `docs/DESIGN-R7.md` section 6 covers that.

use rockfish_hip_emit::Hip;
use rockfish_hip_parse::HIP;
use unpopped::backend::{Backend, DtypeSupport, LowerError};
use unpopped::convert::lift_elementwise;
use unpopped::generate;
use unpopped::ir::{BinaryOp, Expr, OpDef, ScalarExpr, UnaryOp, input, konst};
use unpopped::plan::{KernelPlan, Schedule, try_build_plan};
use unpopped_vocab::{
    ArchSku, ElementKind, OpCategory, OperandDesc, StructureKey, TargetId, structure_key,
};

const F32: &[ElementKind] = &[ElementKind::F32];

fn target(s: &str) -> TargetId {
    TargetId::parse(s).unwrap_or_else(|e| panic!("{s}: {e:?}"))
}

/// An elementwise cell with `n_in` inputs and one output, all contiguous `dt`. `align` 4 defeats
/// vectorization (so the plan is `Schedule::Scalar`); 256 allows it.
fn key_for(n_in: usize, dt: ElementKind, tgt: impl Into<TargetId>, align: u32) -> StructureKey {
    let a = OperandDesc::new(1, &[1 << 20], &[1], dt, align);
    let cat = match n_in {
        1 => OpCategory::UnaryElementwise,
        2 => OpCategory::BinaryElementwise,
        3 => OpCategory::TernaryElementwise,
        _ => panic!("no elementwise category for {n_in} inputs"),
    };
    let operands = vec![a; n_in + 1];
    structure_key(cat, &operands, tgt)
}

fn gfx906_key(n_in: usize) -> StructureKey {
    key_for(n_in, ElementKind::F32, target("rocm:gfx906"), 4)
}

fn op(name: &str, n_in: u8, body: Expr) -> OpDef {
    OpDef::elementwise(name, n_in, F32, body)
}

/// Lower exactly the IR given (no optimizer pass), on the scalar cell.
fn lower_op(o: &OpDef) -> Result<String, LowerError> {
    let key = gfx906_key(o.n_inputs as usize);
    let plan = try_build_plan(o, &key).expect("plan");
    assert_eq!(plan.schedule, Schedule::Scalar, "test cell must be scalar");
    Hip.lower(&plan).map(|k| k.source)
}

fn lifts_to(src: &str, n_in: u8) -> ScalarExpr {
    let l = lift_elementwise(&HIP, src, "x", F32).unwrap_or_else(|e| panic!("{e:?}\n{src}"));
    assert_eq!(l.n_inputs, n_in);
    l.op.body
}

#[test]
fn identity_of_the_backend() {
    assert_eq!(Hip.name(), "hip");
    assert_eq!(Hip.provider(), "rockfish");
}

/// Reviewed by reading. If the emitter changes this text, read the diff; do not regenerate it.
#[test]
fn golden_affine_kernel() {
    let o = op("affine", 2, input(0) * input(1) + input(0));
    let key = gfx906_key(2);
    let got = lower_op(&o).unwrap();
    let want = format!(
        "// Generated by rockfish-hip-emit (hip backend) - do not edit.\n\
         // op: affine | cell: {}\n\
         #include <hip/hip_runtime.h>\n\
         \n\
         extern \"C\" __global__ void rockfish_hip_affine_f32(\n\
         \x20   const float* in0,\n\
         \x20   const float* in1,\n\
         \x20   float* out,\n\
         \x20   long long n)\n\
         {{\n\
         \x20   #pragma clang fp contract(off)\n\
         \x20   for (long long i = (long long)blockIdx.x * blockDim.x + threadIdx.x; i < n;\n\
         \x20        i += (long long)gridDim.x * blockDim.x) {{\n\
         \x20       out[i] = ((in0[i] * in1[i]) + in0[i]);\n\
         \x20   }}\n\
         }}\n",
        key.to_token()
    );
    assert_eq!(got, want);
}

#[test]
fn a_shared_subexpression_is_hoisted_inside_the_loop() {
    // sqrt(x) used twice: the walker names it once.
    let s = input(0).unary(UnaryOp::Sqrt);
    let o = op("twice", 1, s.clone() * s);
    let src = lower_op(&o).unwrap();
    assert_eq!(src.matches("sqrtf(in0[i])").count(), 1, "{src}");
    // The hoist is inside the loop body (after the `{` of the for), not before it.
    let for_at = src.find("for (").unwrap();
    let decl_at = src.find("float t").expect("a hoisted temporary");
    assert!(decl_at > for_at, "{src}");
}

#[test]
fn generate_names_the_kernel_and_goes_through_the_optimizer() {
    let o = op("affine", 2, input(0) * input(1) + input(0));
    let k = generate(&o, &gfx906_key(2), &Hip);
    assert_eq!(k.name, "rockfish_hip_affine_f32");
    assert!(
        k.source
            .contains("extern \"C\" __global__ void rockfish_hip_affine_f32(")
    );
}

// ---- round trip: emit -> parse with HIP -> the IR we started from -------------------------

fn round_trip_cases() -> Vec<(&'static str, u8, Expr)> {
    let mut v: Vec<(&'static str, u8, Expr)> = vec![
        (
            "arith",
            3,
            (input(0) + input(1)) * input(2) - input(0) / input(1),
        ),
        ("constants", 1, input(0) * konst(0.5) + konst(2.0)),
        ("negative constant", 1, input(0) * konst(-1.5)),
    ];
    for (name, u) in [
        ("neg", UnaryOp::Neg),
        ("abs", UnaryOp::Abs),
        ("sqrt", UnaryOp::Sqrt),
        ("exp", UnaryOp::Exp),
        ("log", UnaryOp::Log),
        ("tanh", UnaryOp::Tanh),
        ("sin", UnaryOp::Sin),
        ("cos", UnaryOp::Cos),
        ("floor", UnaryOp::Floor),
        ("ceil", UnaryOp::Ceil),
        ("trunc", UnaryOp::Trunc),
        ("exp2", UnaryOp::Exp2),
    ] {
        v.push((name, 1, input(0).unary(u)));
    }
    for (name, b) in [
        ("fmax", BinaryOp::FmaxIeee),
        ("fmin", BinaryOp::FminIeee),
        ("pow", BinaryOp::Pow),
        ("atan2", BinaryOp::Atan2),
        ("copysign", BinaryOp::Copysign),
    ] {
        v.push((name, 2, input(0).binary(b, input(1))));
    }
    v
}

#[test]
fn every_spelled_op_round_trips_through_the_hip_frontend() {
    let cases = round_trip_cases();
    assert!(cases.len() >= 20, "case list shrank: {}", cases.len());
    for (name, n_in, body) in cases {
        let o = op(name.replace(' ', "_").as_str(), n_in, body.clone());
        let src = lower_op(&o).unwrap_or_else(|e| panic!("{name}: {e}"));
        assert_eq!(lifts_to(&src, n_in), body.0, "{name}\n{src}");
    }
}

/// Control for the test above: the same comparison must be able to fail. Change one operator in
/// the emitted text and the lifted IR must differ from the original (and the unchanged text must
/// not), or the round trip proves nothing.
#[test]
fn control_one_operator_change_breaks_the_round_trip() {
    let body = input(0) + input(1);
    let o = op("plus", 2, body.clone());
    let src = lower_op(&o).unwrap();
    assert_eq!(lifts_to(&src, 2), body.0, "unmutated text must round trip");

    assert_eq!(
        src.matches("(in0[i] + in1[i])").count(),
        1,
        "anchor not found:\n{src}"
    );
    let mutated = src.replace("(in0[i] + in1[i])", "(in0[i] - in1[i])");
    assert_ne!(mutated, src);
    assert_ne!(lifts_to(&mutated, 2), body.0);

    // And a changed function name (expf -> logf) is seen the same way.
    let e = input(0).unary(UnaryOp::Exp);
    let src = lower_op(&op("e", 1, e.clone())).unwrap();
    assert_eq!(src.matches("expf(").count(), 1);
    assert_ne!(lifts_to(&src.replace("expf(", "logf("), 1), e.0);
}

// ---- refusals are typed, and each has a control that lowers ------------------------------

fn is_unsupported_op(r: &Result<String, LowerError>) -> bool {
    matches!(r, Err(LowerError::UnsupportedOp { .. }))
}

#[test]
fn unspelled_unary_ops_are_refused_not_approximated() {
    // Control: a spelled unary lowers, so the refusals below come from the op.
    assert!(lower_op(&op("c", 1, input(0).unary(UnaryOp::Exp))).is_ok());
    for u in [
        UnaryOp::Sqr,
        UnaryOp::Rsqrt,
        UnaryOp::Recip,
        UnaryOp::Sigmoid,
        UnaryOp::Relu,
        UnaryOp::Erf,
        UnaryOp::Gelu,
        UnaryOp::Silu,
        UnaryOp::Round,
        UnaryOp::Sign,
        UnaryOp::Step,
        UnaryOp::Log2,
        UnaryOp::Sinh,
        UnaryOp::Cbrt,
        UnaryOp::Lgamma,
    ] {
        let r = lower_op(&op("u", 1, input(0).unary(u)));
        assert!(is_unsupported_op(&r), "{u:?}: {r:?}");
    }
}

#[test]
fn unspelled_binary_and_ternary_ops_are_refused() {
    assert!(lower_op(&op("c", 2, input(0).binary(BinaryOp::FmaxIeee, input(1)))).is_ok());
    for b in [
        BinaryOp::Max,
        BinaryOp::Min,
        BinaryOp::Rem,
        BinaryOp::RemTrunc,
        BinaryOp::Nextafter,
        BinaryOp::CmpLt,
        BinaryOp::CmpEq,
    ] {
        let r = lower_op(&op("b", 2, input(0).binary(b, input(1))));
        assert!(is_unsupported_op(&r), "{b:?}: {r:?}");
    }
    // A fused multiply-add is one rounding; spelling it as `a * b + c` would be two. Refused.
    let fma = lower_op(&op("f", 3, input(0).fma(input(1), input(2))));
    assert!(is_unsupported_op(&fma), "{fma:?}");
    let sel = lower_op(&op("s", 3, input(0).select(input(1), input(2))));
    assert!(is_unsupported_op(&sel), "{sel:?}");
}

/// The constant `c` in a lifted `Mul(Input(0), Const(c))`.
fn lifted_const(src: &str) -> f64 {
    match lifts_to(src, 1) {
        ScalarExpr::Mul(a, b) => match (*a, *b) {
            (ScalarExpr::Input(0), ScalarExpr::Const(c)) => c,
            other => panic!("unexpected shape {other:?}"),
        },
        other => panic!("unexpected shape {other:?}"),
    }
}

/// The IR rounds a constant to f32 (RNE) at an f32 compute dtype, and the emitter spells that
/// rounded value. The HIP frontend reads a literal's digits as an `f64`, so the lifted constant
/// is not bit-equal to the authored `f64`; it is equal after the same f32 rounding, which is
/// the comparison that means "same value in the kernel".
#[test]
fn constants_are_spelled_as_the_f32_the_ir_rounds_them_to() {
    // 0.1 is not an f32; `generate` does not optimize, so it reaches the emitter as f64 0.1.
    let k = generate(&op("k", 1, input(0) * konst(0.1)), &gfx906_key(1), &Hip);
    assert!(k.source.contains("(in0[i] * 0.1f)"), "{}", k.source);
    assert_eq!(lifted_const(&k.source) as f32, 0.1_f32);

    for v in [1e-7_f64, 3.0e30, -2.7932066917419434, 16777217.0, 1.0e-40] {
        let src = lower_op(&op("k", 1, input(0) * konst(v))).unwrap();
        assert_eq!(lifted_const(&src) as f32, v as f32, "{v}\n{src}");
    }
    // Control: the comparison can fail. The wrong constant is seen.
    let src = lower_op(&op("k", 1, input(0) * konst(0.1))).unwrap();
    assert_ne!(lifted_const(&src) as f32, 0.2_f32);
}

#[test]
fn constants_that_change_class_are_refused() {
    assert!(lower_op(&op("c", 1, input(0) + konst(0.5))).is_ok());
    for (what, v) in [
        ("nan", f64::NAN),
        ("inf", f64::INFINITY),
        ("-inf", f64::NEG_INFINITY),
        ("overflows f32", 1e300),
        ("underflows f32 to zero", 1e-300),
    ] {
        let r = lower_op(&op("k", 1, input(0) + konst(v)));
        assert!(is_unsupported_op(&r), "{what}: {r:?}");
    }
    // Zero is zero, not an underflow.
    assert!(lower_op(&op("z", 1, input(0) + konst(0.0))).is_ok());
}

#[test]
fn only_f32_on_a_rocm_target_is_supported() {
    for t in ["rocm:gfx906", "rocm:gfx1036", "rocm:gfx942"] {
        assert_eq!(
            Hip.supports_dtype(ElementKind::F32, target(t)),
            DtypeSupport::Supported,
            "{t}"
        );
        for dt in [
            ElementKind::F16,
            ElementKind::Bf16,
            ElementKind::F64,
            ElementKind::F32Strict,
            ElementKind::I32,
            ElementKind::U8,
            ElementKind::Bool,
        ] {
            assert_eq!(
                Hip.supports_dtype(dt, target(t)),
                DtypeSupport::Unsupported,
                "{dt:?} on {t}"
            );
        }
    }
    // A target outside the rocm namespace: f32 itself is not claimed.
    assert_eq!(
        Hip.supports_dtype(ElementKind::F32, ArchSku::Sm89.into()),
        DtypeSupport::Unsupported
    );
}

#[test]
fn lowering_an_unsupported_dtype_or_target_is_a_typed_error() {
    let o = OpDef::elementwise("h", 1, &[ElementKind::F16], input(0) + input(0));
    let key = key_for(1, ElementKind::F16, target("rocm:gfx906"), 4);
    let plan = try_build_plan(&o, &key).expect("plan");
    assert!(matches!(
        Hip.lower(&plan),
        Err(LowerError::UnsupportedDtype {
            dtype: ElementKind::F16,
            ..
        })
    ));

    let o = op("c", 1, input(0) + input(0));
    let key = key_for(1, ElementKind::F32, ArchSku::Sm89, 4);
    let plan = try_build_plan(&o, &key).expect("plan");
    assert!(matches!(
        Hip.lower(&plan),
        Err(LowerError::UnsupportedDtype {
            dtype: ElementKind::F32,
            ..
        })
    ));
}

fn vec_plan_for<'a>(o: &'a OpDef, key: &'a StructureKey) -> KernelPlan<'a> {
    let plan = try_build_plan(o, key).unwrap();
    assert!(
        matches!(plan.schedule, Schedule::Vectorized { .. }),
        "expected a vectorized cell, got {:?}",
        plan.schedule
    );
    plan
}

#[test]
fn a_vectorized_cell_lowers_with_vector_loads_and_a_scalar_tail() {
    let o = op("v", 2, input(0) + input(1));
    let key = key_for(2, ElementKind::F32, target("rocm:gfx906"), 256);
    let plan = vec_plan_for(&o, &key);
    let Schedule::Vectorized { width } = plan.schedule else {
        unreachable!()
    };
    let src = Hip.lower(&plan).expect("a vectorized cell lowers").source;
    let (vty, lanes): (&str, &[&str]) = match width {
        2 => ("float2", &["x", "y"]),
        4 => ("float4", &["x", "y", "z", "w"]),
        w => panic!("unexpected width {w}"),
    };
    assert!(
        src.contains(&format!(
            "const {vty}* v0 = reinterpret_cast<const {vty}*>(in0);"
        )),
        "{src}"
    );
    assert!(
        src.contains(&format!("{vty}* vout = reinterpret_cast<{vty}*>(out);")),
        "{src}"
    );
    assert!(
        src.contains(&format!("const long long nv = n / {width};")),
        "{src}"
    );
    for lane in lanes {
        assert!(
            src.contains(&format!("r.{lane} = (a0.{lane} + a1.{lane});")),
            "lane {lane} missing:
{src}"
        );
    }
    // The scalar tail covers exactly the elements the vector loop did not.
    assert!(src.contains(&format!("i = nv * {width} +")), "{src}");
    assert!(src.contains("out[i] = (in0[i] + in1[i]);"), "{src}");
    assert!(src.contains("#pragma clang fp contract(off)"), "{src}");
}

#[test]
fn a_shared_subexpression_in_a_vector_lane_is_hoisted_inside_that_lanes_block() {
    let t = input(0) * input(1);
    let o = op("vs", 2, t.clone() + t);
    let key = key_for(2, ElementKind::F32, target("rocm:gfx906"), 256);
    let src = Hip.lower(&vec_plan_for(&o, &key)).unwrap().source;
    // Every lane block is its own scope, so the temporaries of two lanes cannot collide.
    let opens = src
        .matches(
            "        {
",
        )
        .count();
    let Schedule::Vectorized { width } = try_build_plan(&o, &key).unwrap().schedule else {
        unreachable!()
    };
    assert_eq!(opens, width as usize, "{src}");
}

#[test]
fn a_vector_width_that_is_not_spelled_is_refused_not_narrowed() {
    let o = op("w8", 1, input(0) + input(0));
    let key = key_for(1, ElementKind::F32, target("rocm:gfx906"), 256);
    let mut plan = vec_plan_for(&o, &key);
    plan.schedule = Schedule::Vectorized { width: 8 };
    assert!(matches!(
        Hip.lower(&plan),
        Err(LowerError::UnsupportedPlanShape { .. })
    ));
    // Control: the same plan at a spelled width lowers.
    plan.schedule = Schedule::Vectorized { width: 4 };
    assert!(Hip.lower(&plan).is_ok());
}

#[test]
fn the_vector_lanes_are_the_scalar_body_over_that_lanes_components() {
    // Same op on the scalar cell: its body, with `inN[i]` rewritten to `aN.<lane>`, is lane x.
    let o = op("eq", 2, (input(0) - input(1)) * konst(0.5));
    let scalar = lower_op(&o).unwrap();
    let key = key_for(2, ElementKind::F32, target("rocm:gfx906"), 256);
    let vec_src = Hip.lower(&vec_plan_for(&o, &key)).unwrap().source;
    let scalar_rhs = scalar
        .lines()
        .find_map(|l| l.trim().strip_prefix("out[i] = "))
        .expect("scalar store");
    let lane_x = scalar_rhs
        .replace("in0[i]", "a0.x")
        .replace("in1[i]", "a1.x");
    assert!(
        vec_src.contains(&format!("r.x = {lane_x}")),
        "{lane_x}
{vec_src}"
    );
}

#[test]
fn an_op_name_that_is_not_an_identifier_is_refused() {
    for bad in ["has space", "new\nline", "a-b", "x();", ""] {
        let o = op(bad, 1, input(0) + input(0));
        let key = gfx906_key(1);
        // Measured: the plan gate accepts every one of these names, so the refusal under test
        // is the emitter's. If a core release starts refusing a name first, this panics and
        // says so, instead of the test passing without exercising the emitter.
        let plan = try_build_plan(&o, &key).unwrap_or_else(|e| panic!("{bad:?}: gate: {e:?}"));
        assert!(
            matches!(
                Hip.lower(&plan),
                Err(LowerError::UnsupportedPlanShape { .. })
            ),
            "{bad:?}"
        );
    }
    // Control: a plain name lowers.
    assert!(lower_op(&op("fine_name_1", 1, input(0) + input(0))).is_ok());
}

#[test]
fn a_runtime_parameter_is_a_trailing_float_argument_and_the_body_reads_it() {
    let o = op(
        "p",
        1,
        input(0) * unpopped::ir::param(1) + unpopped::ir::param(0),
    );
    let src = lower_op(&o).expect("a Param body lowers");
    // Ascending by index, after the last fixed argument.
    assert!(
        src.contains("    long long n,\n    float p0,\n    float p1)\n{\n"),
        "{src}"
    );
    assert!(src.contains("(in0[i] * p1)") && src.contains("p0"), "{src}");
    // Control: an op with no param declares none.
    let none = lower_op(&op("np", 1, input(0) + input(0))).unwrap();
    assert!(!none.contains("float p"), "{none}");
    assert!(none.contains("    long long n)\n{\n"), "{none}");
}

#[test]
fn only_the_params_the_body_reads_are_declared_even_when_sparse() {
    let src = lower_op(&op("sp", 1, input(0) + unpopped::ir::param(2))).unwrap();
    assert!(src.contains("    float p2)\n{\n"), "{src}");
    assert!(
        !src.contains("float p0") && !src.contains("float p1"),
        "{src}"
    );
}

#[test]
fn a_vectorized_kernel_takes_its_params_as_scalar_floats_used_by_every_lane() {
    let o = op("vp", 1, input(0) * unpopped::ir::param(0));
    let key = key_for(1, ElementKind::F32, target("rocm:gfx906"), 256);
    let plan = vec_plan_for(&o, &key);
    let Schedule::Vectorized { width } = plan.schedule else {
        unreachable!()
    };
    let src = Hip.lower(&plan).unwrap().source;
    assert!(src.contains("    float p0)\n{\n"), "{src}");
    assert!(
        !src.contains("float2 p0") && !src.contains("float4 p0"),
        "{src}"
    );
    assert_eq!(src.matches("* p0)").count(), width as usize + 1, "{src}");
}

#[test]
fn an_input_past_the_declared_operands_is_refused() {
    // Declares one input, reads input 1.
    let o = op("oob", 1, input(0) + input(1));
    let key = gfx906_key(1);
    let plan = try_build_plan(&o, &key).unwrap_or_else(|e| panic!("gate: {e:?}"));
    let r = Hip.lower(&plan);
    assert!(
        matches!(r, Err(LowerError::UnsupportedOp { .. })),
        "emitted a read of an undeclared input: {r:?}"
    );
}
