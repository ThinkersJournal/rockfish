//! Tests for the reduction and scan schedules of [`rockfish_hip_emit::Hip`] (R7c).
//!
//! **What these show.** The emitted text is what is reviewed here, and everything outside the
//! emitted shapes is a typed refusal with a control that lowers. **What they do not show:** that
//! the text compiles under a HIP compiler or computes the right numbers on a GPU (no HIP
//! compiler on this machine; the rig rows in `docs/DESIGN-R7.md` section 6 cover that).

use rockfish_hip_emit::Hip;
use unpopped::backend::{Backend, LowerError};
use unpopped::ir::{Expr, OpDef, ReduceOp, input};
use unpopped::plan::{KernelPlan, ReduceAxisClass, Schedule, try_build_plan};
use unpopped_vocab::{ElementKind, OpCategory, OperandDesc, StructureKey, TargetId, structure_key};

const F32: &[ElementKind] = &[ElementKind::F32];

fn gfx906() -> TargetId {
    TargetId::parse("rocm:gfx906").unwrap()
}

fn mat() -> OperandDesc {
    OperandDesc::new(2, &[64, 1024], &[1024, 1], ElementKind::F32, 4)
}

fn row_vec() -> OperandDesc {
    OperandDesc::new(1, &[64], &[1], ElementKind::F32, 4)
}

fn reduction_key() -> StructureKey {
    structure_key(OpCategory::Reduction, &[mat(), row_vec()], gfx906())
}

fn scan_key() -> StructureKey {
    structure_key(OpCategory::Scan, &[mat(), mat()], gfx906())
}

fn lower_plan(plan: &KernelPlan<'_>) -> Result<String, LowerError> {
    Hip.lower(plan).map(|k| k.source)
}

fn reduce(op: ReduceOp, body: Expr) -> Result<String, LowerError> {
    let o = OpDef::reduction("red", 1, F32, body, op);
    let key = reduction_key();
    let plan = try_build_plan(&o, &key).expect("plan");
    assert!(
        matches!(plan.schedule, Schedule::Reduction { .. }),
        "{:?}",
        plan.schedule
    );
    lower_plan(&plan)
}

fn scan(op: ReduceOp, reverse: bool, exclusive: bool) -> Result<String, LowerError> {
    let o = OpDef::scan(
        "scn",
        1,
        F32,
        op,
        1,
        reverse,
        exclusive,
        input(0),
        unpopped::ir::reduced(0),
    );
    let key = scan_key();
    let plan = try_build_plan(&o, &key).expect("plan");
    lower_plan(&plan)
}

/// Reviewed by reading. If the emitter changes this text, read the diff; do not regenerate it.
#[test]
fn golden_sum_reduction() {
    let got = reduce(ReduceOp::Sum, input(0)).unwrap();
    let want = format!(
        "// Generated by rockfish-hip-emit (hip backend) - do not edit.\n\
         // op: red (reduction) | cell: {}\n\
         #include <hip/hip_runtime.h>\n\
         \n\
         extern \"C\" __global__ void rockfish_hip_red_f32(\n\
         \x20   const float* in0,\n\
         \x20   float* out,\n\
         \x20   long long rows,\n\
         \x20   long long k)\n\
         {{\n\
         \x20   #pragma clang fp contract(off)\n\
         \x20   for (long long r = (long long)blockIdx.x * blockDim.x + threadIdx.x; r < rows;\n\
         \x20        r += (long long)gridDim.x * blockDim.x) {{\n\
         \x20       double acc = 0.0;\n\
         \x20       for (long long j = 0; j < k; ++j) {{\n\
         \x20           double v = (double)(in0[r * k + j]);\n\
         \x20           acc = acc + v;\n\
         \x20       }}\n\
         \x20       out[r] = (float)(acc);\n\
         \x20   }}\n\
         }}\n",
        reduction_key().to_token()
    );
    assert_eq!(got, want);
}

/// Reviewed by reading: an exclusive reverse max scan (the flags that change the most text).
#[test]
fn golden_exclusive_reverse_max_scan() {
    let got = scan(ReduceOp::Max, true, true).unwrap();
    let want = format!(
        "// Generated by rockfish-hip-emit (hip backend) - do not edit.\n\
         // op: scn (scan) | cell: {}\n\
         #include <hip/hip_runtime.h>\n\
         \n\
         extern \"C\" __global__ void rockfish_hip_scn_f32(\n\
         \x20   const float* in0,\n\
         \x20   float* out,\n\
         \x20   long long rows,\n\
         \x20   long long k)\n\
         {{\n\
         \x20   #pragma clang fp contract(off)\n\
         \x20   for (long long r = (long long)blockIdx.x * blockDim.x + threadIdx.x; r < rows;\n\
         \x20        r += (long long)gridDim.x * blockDim.x) {{\n\
         \x20       double acc = -__builtin_inf();\n\
         \x20       for (long long t = 0; t < k; ++t) {{\n\
         \x20           long long j = k - 1 - t;\n\
         \x20           double v = (double)(in0[r * k + j]);\n\
         \x20           out[r * k + j] = (float)acc;\n\
         \x20           if (v != v || v > acc) {{ acc = v; }}\n\
         \x20       }}\n\
         \x20   }}\n\
         }}\n",
        scan_key().to_token()
    );
    assert_eq!(got, want);
}

#[test]
fn every_reduce_op_has_its_own_combine_and_identity() {
    let cases = [
        (ReduceOp::Sum, "double acc = 0.0;", "acc = acc + v;"),
        (ReduceOp::Mean, "double acc = 0.0;", "acc / (double)k"),
        (ReduceOp::Prod, "double acc = 1.0;", "acc = acc * v;"),
        (ReduceOp::Max, "bool have = false;", "v > acc"),
        (ReduceOp::Min, "bool have = false;", "v < acc"),
    ];
    let mut seen = Vec::new();
    for (op, init, fold) in cases {
        let src = reduce(op, input(0)).unwrap_or_else(|e| panic!("{op:?}: {e}"));
        assert!(src.contains(init), "{op:?}: {src}");
        assert!(src.contains(fold), "{op:?}: {src}");
        seen.push(src);
    }
    // Control: the five texts are pairwise different, so the asserts above are not all matching
    // one shared line.
    for i in 0..seen.len() {
        for j in i + 1..seen.len() {
            assert_ne!(seen[i], seen[j], "{i} vs {j}");
        }
    }
}

#[test]
fn the_pre_reduction_body_is_lowered_over_the_row_offset() {
    let src = reduce(ReduceOp::Sum, input(0) * input(0)).unwrap();
    assert!(src.contains("(in0[r * k + j] * in0[r * k + j])"), "{src}");
}

#[test]
fn a_reduction_and_a_scan_declare_the_params_their_pre_body_reads() {
    use unpopped::ir::param;
    let red = reduce(ReduceOp::Sum, input(0) * param(0)).unwrap();
    assert!(
        red.contains("    long long k,\n    float p0)\n{\n"),
        "{red}"
    );
    assert!(red.contains("(in0[r * k + j] * p0)"), "{red}");

    let o = OpDef::scan(
        "scp",
        1,
        F32,
        ReduceOp::Sum,
        1,
        false,
        false,
        input(0) + param(1),
        unpopped::ir::reduced(0),
    );
    let key = scan_key();
    let plan = try_build_plan(&o, &key).expect("plan");
    let scn = lower_plan(&plan).unwrap();
    assert!(
        scn.contains("    long long k,\n    float p1)\n{\n"),
        "{scn}"
    );
    // Control: the param-free forms declare none.
    assert!(!reduce(ReduceOp::Sum, input(0)).unwrap().contains("float p"));
}

#[test]
fn scan_flags_change_the_text_and_each_op_lowers() {
    let base = scan(ReduceOp::Sum, false, false).unwrap();
    let rev = scan(ReduceOp::Sum, true, false).unwrap();
    let excl = scan(ReduceOp::Sum, false, true).unwrap();
    assert!(base.contains("long long j = t;"), "{base}");
    assert!(rev.contains("long long j = k - 1 - t;"), "{rev}");
    // Inclusive stores after the combine; exclusive stores before it.
    let store = "out[r * k + j] = (float)acc;";
    let combine = "acc = acc + v;";
    assert!(base.find(store).unwrap() > base.find(combine).unwrap());
    assert!(excl.find(store).unwrap() < excl.find(combine).unwrap());
    for op in [ReduceOp::Sum, ReduceOp::Prod, ReduceOp::Max, ReduceOp::Min] {
        scan(op, false, false).unwrap_or_else(|e| panic!("{op:?}: {e}"));
    }
    let imax = scan(ReduceOp::Max, false, false).unwrap();
    let imin = scan(ReduceOp::Min, false, false).unwrap();
    assert!(imax.contains("-__builtin_inf()") && imax.contains("v > acc"));
    assert!(imin.contains("= __builtin_inf()") && imin.contains("v < acc"));
}

#[test]
fn only_the_inner_contiguous_reduce_axis_is_emitted() {
    // Control: the default (last-axis) reduction lowers.
    assert!(reduce(ReduceOp::Sum, input(0)).is_ok());
    let o = OpDef::reduction("red", 1, F32, input(0), ReduceOp::Sum);
    let key = reduction_key();
    let mut plan = try_build_plan(&o, &key).expect("plan");
    let Schedule::Reduction { op, keepdim, .. } = plan.schedule else {
        panic!("{:?}", plan.schedule)
    };
    for class in [
        ReduceAxisClass::Outer,
        ReduceAxisClass::Middle,
        ReduceAxisClass::Multi,
    ] {
        plan.schedule = Schedule::Reduction { op, class, keepdim };
        let r = lower_plan(&plan);
        assert!(
            matches!(r, Err(LowerError::UnsupportedSchedule { .. })),
            "{class:?}: {r:?}"
        );
    }
}

#[test]
fn a_fused_post_expression_is_refused() {
    let ok = OpDef::reduction("red", 1, F32, input(0), ReduceOp::Sum);
    let post = OpDef::reduction_post(
        "red",
        1,
        F32,
        input(0),
        ReduceOp::Sum,
        unpopped::ir::reduced(0).sqrt(),
    );
    let key = reduction_key();
    let p_ok = try_build_plan(&ok, &key).expect("plan");
    assert!(lower_plan(&p_ok).is_ok(), "control must lower");
    let p_post = try_build_plan(&post, &key).expect("plan");
    let r = lower_plan(&p_post);
    assert!(
        matches!(r, Err(LowerError::UnsupportedPlanShape { .. })),
        "{r:?}"
    );

    let scan_post = OpDef::scan(
        "scn",
        1,
        F32,
        ReduceOp::Sum,
        1,
        false,
        false,
        input(0),
        unpopped::ir::reduced(0).sqrt(),
    );
    let skey = scan_key();
    let r = lower_plan(&try_build_plan(&scan_post, &skey).expect("plan"));
    assert!(
        matches!(r, Err(LowerError::UnsupportedPlanShape { .. })),
        "{r:?}"
    );
}

