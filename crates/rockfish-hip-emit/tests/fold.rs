#[test]
fn a_scan_has_no_mean() {
    // `build_plan` rejects Mean for a scan, so build the plan with Sum and swap the op: this is
    // the emitter's own guard, for a plan built some other way.
    let o = OpDef::scan(
        "scn",
        1,
        F32,
        ReduceOp::Sum,
        1,
        false,
        false,
        input(0),
        unpopped::ir::reduced(0),
    );
    let key = scan_key();
    let mut plan = try_build_plan(&o, &key).expect("plan");
    plan.schedule = Schedule::Scan {
        op: ReduceOp::Mean,
        axis: 1,
        reverse: false,
        exclusive: false,
        block: false,
    };
    let r = lower_plan(&plan);
    assert!(
        matches!(r, Err(LowerError::UnsupportedPlanShape { .. })),
        "{r:?}"
    );
}

#[test]
fn a_reduction_does_not_use_a_warp_width() {
    // The serial schedules need no wavefront size; nothing here may assume 32 (or 64).
    for src in [
        reduce(ReduceOp::Sum, input(0)).unwrap(),
        scan(ReduceOp::Sum, false, false).unwrap(),
    ] {
        for banned in [
            "warpSize",
            "__shfl",
            "__syncthreads",
            "__shared__",
            "32",
            "64",
        ] {
            // The header comment carries the cell token (`ix32`) and the symbol ends `_f32`:
            // look past the first and drop the second, so a digit left is a width.
            let body = src
                .split("\n#include")
                .nth(1)
                .unwrap()
                .replace("_f32(", "(");
            assert!(!body.contains(banned), "{banned} in\n{src}");
        }
    }
}
